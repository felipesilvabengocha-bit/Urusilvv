export function createInitialFiscalLedger(
  macro: MacroSnapshot,
  budget: BudgetAllocation[],
  revenues: RevenueLineItem[],
  debtProfile: DebtProfile,
  mix: DeficitFinancingMix
): FiscalLedgerSummary {
  const nominalGdpUYU = Math.max(100, macro.gdpBillionsUSD * macro.exchangeRateUYU);
  const totalBudgetUYU = budget.reduce((s, b) => s + b.annualBillionsUYU, 0);
  const totalExecutedUYU = budget.reduce((s, b) => s + (b.executedBillionsUYU ?? b.annualBillionsUYU * 0.94), 0);
  const totalCommittedUYU = budget.reduce((s, b) => s + (b.committedBillionsUYU ?? b.annualBillionsUYU * 0.97), 0);
  const projectedRevUYU = revenues.reduce((s, r) => s + r.projectedBillionsUYU, 0);
  const collectedRevUYU = revenues.reduce((s, r) => s + r.collectedBillionsUYU, 0);

  const interestItem = budget.find((b) => b.category === 'intereses_otros');
  const debtInterestPctGdp = Number(
    (macro.debtInterestPctGdp ?? ((interestItem?.annualBillionsUYU ?? nominalGdpUYU * 0.025) / nominalGdpUYU) * 100).toFixed(2)
  );
  const currentSpendingPctGdp = Number(((totalBudgetUYU / nominalGdpUYU) * 100).toFixed(2));
  const executedSpendingPctGdp = Number(((totalExecutedUYU / nominalGdpUYU) * 100).toFixed(2));
  const projectedRevenuePctGdp = Number(((projectedRevUYU / nominalGdpUYU) * 100).toFixed(2));
  const collectedRevenuePctGdp = Number(((collectedRevUYU / nominalGdpUYU) * 100).toFixed(2));
  const primarySpendingPct = Math.max(0, executedSpendingPctGdp - debtInterestPctGdp);
  const primaryBalancePctGdp = Number((collectedRevenuePctGdp - primarySpendingPct).toFixed(2));
  const globalBalancePctGdp = Number((primaryBalancePctGdp - debtInterestPctGdp).toFixed(2));

  const taxBurdenPctGdp = Number(
    revenues
      .filter((r) => r.id !== 'empresas_publicas' && r.id !== 'otros_ingresos')
      .reduce((s, r) => s + r.pctOfGdp, 0)
      .toFixed(2)
  );

  const avgFinancingCostPct = Number(
    (
      debtProfile.weightedAvgRatePct * ((mix.internalDebtUiUyuPct + mix.externalDebtMultilateralPct) / 100) +
      1.8 * (mix.treasuryAssetsDrawPct / 100)
    ).toFixed(2)
  );

  const sustainabilityIndex = Math.max(
    15,
    Math.min(
      98,
      Math.round(84 - Math.max(0, -globalBalancePctGdp - 2.0) * 6 - Math.max(0, macro.grossDebtPctGdp - 60) * 0.55 - macro.countryRiskBps / 25)
    )
  );

  return {
    projectedRevenuePctGdp,
    collectedRevenuePctGdp,
    approvedSpendingPctGdp: currentSpendingPctGdp,
    currentSpendingPctGdp,
    committedSpendingPctGdp: Number(((totalCommittedUYU / nominalGdpUYU) * 100).toFixed(2)),
    executedSpendingPctGdp,
    primaryBalancePctGdp,
    debtInterestPctGdp,
    globalBalancePctGdp,
    taxBurdenPctGdp,
    avgFinancingCostPct,
    sustainabilityIndex,
  };
}

export function scaleNationalBudgetToMacro(macro: MacroSnapshot): BudgetAllocation[] {
  const nominalGdpUYU = Math.max(100, macro.gdpBillionsUSD * macro.exchangeRateUYU);
  const baseTotal = INITIAL_NATIONAL_BUDGET.reduce((s, b) => s + b.annualBillionsUYU, 0);
  const targetTotalUYU = (macro.spendingPctGdp / 100) * nominalGdpUYU;
  const factor = targetTotalUYU / Math.max(1, baseTotal);

  return INITIAL_NATIONAL_BUDGET.map((item) => {
    const annual = Number(Math.max(1.5, item.annualBillionsUYU * factor).toFixed(1));
    const committed = Number((annual * (item.category === 'jubilaciones' || item.category === 'intereses_otros' ? 0.99 : 0.93)).toFixed(1));
    const executed = Number((committed * Math.min(1, item.executionEfficiency / 100 + 0.19)).toFixed(1));
    return {
      ...item,
      annualBillionsUYU: annual,
      approvedBillionsUYU: annual,
      committedBillionsUYU: committed,
      executedBillionsUYU: executed,
      pctOfGdp: Number(((annual / nominalGdpUYU) * 100).toFixed(2)),
    };
  });
}

export function enrichDepartmentTerritorial(dept: DepartmentData): DepartmentData {
  const needsByProfile: string[] = [];
  if (dept.unemploymentRate >= 8.5) needsByProfile.push('Fomento de empleo formal');
  if (dept.povertyRate >= 10.5) needsByProfile.push('Inclusión social y vivienda');
  if (dept.localServiceQuality < 64) needsByProfile.push('Caminería, saneamiento y alumbrado');
  if (dept.economicProfile.some((e) => e.toLowerCase().includes('turismo'))) {
    needsByProfile.push('Infraestructura turística');
  }
  if (needsByProfile.length === 0) needsByProfile.push('Logística productiva y mantenimiento');

  const isTourist = dept.economicProfile.some((p) => p.toLowerCase().includes('turismo'));
  return {
    ...dept,
    economicActivityIndex: dept.economicActivityIndex ?? Number((dept.gdpPerCapitaIndex * 0.96).toFixed(1)),
    employmentRate: dept.employmentRate ?? Number((63.8 - dept.unemploymentRate * 0.65).toFixed(1)),
    infrastructureScore: dept.infrastructureScore ?? Math.round(dept.localServiceQuality * 0.95),
    tourismFlowIndex: dept.tourismFlowIndex ?? (isTourist ? 82 : 44),
    accumulatedInvestmentUYU: dept.accumulatedInvestmentUYU ?? Math.round(dept.annualBudgetMillionsUYU * 0.24),
    territorialNeeds: dept.territorialNeeds ?? needsByProfile,
  };
}

