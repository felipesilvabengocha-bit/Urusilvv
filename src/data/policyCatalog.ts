interface CompactPolicySeed {
  code: string;
  cat: PolicyCategoryCode;
  ori: PolicyOrientation;
  inst: LegalInstrumentType;
  body: string;
  comp: string;
  title: string;
  area: NationalBudgetCategory;
  summary: string;
  fin: string;
  ben: string;
  months: number;
  cp: number;
  money: number;
  risk: 'bajo' | 'medio' | 'alto';
  resist: string[];
  gdp?: number;
  inf?: number;
  unemp?: number;
  pov?: number;
  gini?: number;
  cost?: number;
  rev?: number;
  app?: number;
  pos: string[];
  neg: string[];
  tags: string[];
}

function hydratePolicy(s: CompactPolicySeed): PublicPolicyDraft {
  const gdp = s.gdp ?? 0;
  const inf = s.inf ?? 0;
  const unemp = s.unemp ?? 0;
  const pov = s.pov ?? 0;
  const gini = s.gini ?? 0;
  const cost = s.cost ?? 0.12;
  const rev = s.rev ?? 0;
  const app = s.app ?? 1.2;

  return {
    id: `cat_${s.code.toLowerCase()}`,
    code: s.code,
    categoryCode: s.cat,
    orientation: s.ori,
    legalInstrument: s.inst,
    responsibleBody: s.body,
    requiredCompetence: s.comp,
    normativeText: `${s.code} · ${LEGAL_INSTRUMENT_LABELS[s.inst]} — ${s.summary}`,
    riskLevel: s.risk,
    socialResistance: s.resist,
    targetIndicators: [
      gdp !== 0 ? `PIB (${gdp > 0 ? '+' : ''}${gdp}%)` : '',
      unemp !== 0 ? `Desempleo (${unemp > 0 ? '+' : ''}${unemp}%)` : '',
      pov !== 0 ? `Pobreza (${pov > 0 ? '+' : ''}${pov}%)` : '',
      inf !== 0 ? `Inflación (${inf > 0 ? '+' : ''}${inf}%)` : '',
    ].filter(Boolean),
    title: s.title,
    ministryArea: s.area,
    summary: s.summary,
    objectives: [
      `Ejecutar ${s.title.toLowerCase()} mediante ${LEGAL_INSTRUMENT_LABELS[s.inst].toLowerCase()}.`,
      `Beneficiar directamente a ${s.ben.toLowerCase()}.`,
    ],
    instruments: [LEGAL_INSTRUMENT_LABELS[s.inst], s.body],
    financingSource: s.fin,
    beneficiaries: s.ben,
    timelineMonths: s.months,
    implementationSteps: [
      `Emisión de ${LEGAL_INSTRUMENT_LABELS[s.inst]} por ${s.body}.`,
      'Asignación presupuestal y monitoreo técnico OPP/MEF.',
      `Evaluación de metas e impacto al mes ${Math.round(s.months * 0.6)}.`,
    ],
    conditions: [s.comp, `Financiamiento: ${s.fin}`],
    politicalCapitalCost: s.cp,
    moneyCostUYU: s.money,
    estimatedEffects: {
      gdpDelta: Number((gdp * 0.45).toFixed(2)),
      inflationDelta: Number((inf * 0.5).toFixed(2)),
      unemploymentDelta: Number((unemp * 0.45).toFixed(2)),
      povertyDelta: Number((pov * 0.45).toFixed(2)),
      giniDelta: Number((gini * 0.45).toFixed(3)),
      fiscalCostPctGdp: cost,
      expectedRevenuePctGdp: rev,
      approvalDelta: app,
    },
    delayedEffects: {
      gdpDelta: Number((gdp * 0.75).toFixed(2)),
      inflationDelta: Number((inf * 0.5).toFixed(2)),
      unemploymentDelta: Number((unemp * 0.75).toFixed(2)),
      povertyDelta: Number((pov * 0.75).toFixed(2)),
      giniDelta: Number((gini * 0.75).toFixed(3)),
      productionDelta: Number((gdp * 1.4).toFixed(2)),
      approvalDelta: Number((app * 0.6).toFixed(1)),
    },
    positiveExternalities: s.pos,
    negativeExternalities: s.neg,
    viabilityNote:
      s.inst === 'proyecto_ley' || s.inst === 'ley_presupuestal'
        ? 'Requiere sanción bicameral en Diputados y Senadores antes de entrar en vigor.'
        : 'Ejecutable desde la esfera del Poder Ejecutivo / Ente responsable.',
    synergyTags: s.tags,
  };
}

